const { _electron: electron, expect } = require('playwright/test');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');

(async () => {
  const data = fs.mkdtempSync(path.join(os.tmpdir(), 'logic-reading-compact-'));
  const executablePath = process.env.DUOBOOK_SMOKE_EXECUTABLE || path.resolve('release/mac-arm64/逻辑阅读.app/Contents/MacOS/逻辑阅读');
  const env = { ...process.env, DUOBOOK_SMOKE_DIR: data }; delete env.ELECTRON_RUN_AS_NODE;
  let app;
  let sourcePath, savedBounds, savedText, savedProgress;
  try {
    app = await electron.launch({ executablePath, env, timeout: 60000 });
    const main = await app.firstWindow();
    await main.getByRole('button', { name: '打开工作台' }).click();
    await main.getByRole('heading', { name: '明确目标', exact: true }).waitFor();
    sourcePath = new URL(main.url()).pathname;
    await main.waitForFunction(() => speechSynthesis.getVoices().some((voice) => voice.localService));
    await main.getByRole('button', { name: '开始朗读', exact: true }).click();
    await expect(main.getByLabel('朗读状态')).toContainText('正在朗读');
    const nextWindow = app.waitForEvent('window');
    await main.getByRole('button', { name: '单行阅读', exact: true }).click();
    const compact = await nextWindow;
    const text = compact.getByTestId('compact-text');
    await expect(text).toHaveAttribute('data-start');
    await expect(compact.getByTestId('compact-progress')).toHaveText(/^\d+\.\d{2}%$/);
    await expect(compact.getByTestId('compact-progress')).toHaveAccessibleName('全书进度');
    const initialProgress = await compact.getByTestId('compact-progress').textContent();
    await expect(main.getByLabel('朗读状态')).not.toContainText('正在朗读');
    await expect.poll(() => app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().map((window) => ({ title: window.getTitle(), visible: window.isVisible(), bounds: window.getContentBounds() })))).toEqual(expect.arrayContaining([
      expect.objectContaining({ title: '逻辑阅读', visible: false }), expect.objectContaining({ title: '资料', visible: true, bounds: expect.objectContaining({ width: 600, height: 36 }) }),
    ]));
    assert.equal(await compact.getByRole('button', { name: '拖动阅读条' }).evaluate((element) => getComputedStyle(element).getPropertyValue('-webkit-app-region')), 'drag');
    await compact.getByRole('button', { name: '下一行', exact: true }).click();
    await expect(compact.getByTestId('compact-progress')).not.toHaveText(initialProgress);
    savedText = await text.textContent();
    const source = await compact.evaluate(async () => (await fetch('/api/v1/books/book_learning/chapters/chapter_goal')).json());
    const current = source.reading_progress.paragraphs.find(p => p.paragraph_id === source.paragraphs[0].id);
    await expect(compact.getByTestId('compact-progress')).toHaveText(((current.start_character + Number(await text.getAttribute('data-end'))) / source.reading_progress.total_characters * 100).toFixed(2) + '%');
    const selectLine = async (mouse = false) => {
      if (mouse) {
        const rect = await text.boundingBox();
        await compact.mouse.move(rect.x + 2, rect.y + rect.height / 2); await compact.mouse.down();
        await compact.mouse.move(rect.x + 100, rect.y + rect.height / 2, { steps: 10 }); await compact.mouse.up();
      } else {
        await text.dispatchEvent('pointerdown');
        await text.evaluate(element => { const range = document.createRange(); range.selectNodeContents(element); const selection = getSelection(); selection.removeAllRanges(); selection.addRange(range); element.dispatchEvent(new MouseEvent('mouseup', { bubbles: true })); });
      }
      await expect(compact.getByRole('dialog', { name: '单行划线操作' })).toBeVisible();
      await expect.poll(() => app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(w => w.getTitle() === '资料').getContentBounds().height)).toBe(316);
    };
    await selectLine(true);
    await compact.getByRole('button', { name: '只做摘抄', exact: true }).click();
    await expect(compact.getByRole('dialog', { name: '单行划线操作' })).toHaveCount(0);
    await expect(text.locator('mark')).toHaveCount(1);
    await selectLine(); await compact.getByRole('button', { name: '添加笔记', exact: true }).click();
    await compact.getByLabel('划线笔记内容').fill('单行窗口里的原文批注。');
    await compact.screenshot({ path: 'release/compact-note.png' });
    await compact.getByRole('button', { name: '保存笔记', exact: true }).click();
    await expect(compact.getByRole('dialog', { name: '单行划线操作' })).toHaveCount(0);
    await expect.poll(() => app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(w => w.getTitle() === '资料').getContentBounds().height)).toBe(36);
    await compact.getByRole('button', { name: '更多阅读设置' }).hover();
    await expect(compact.locator('.compact-reader__controls')).toHaveCSS('opacity', '1');
    await compact.screenshot({ path: 'release/compact-book-progress.png' });
    await compact.getByRole('button', { name: '窗口置顶', exact: true }).click();
    await compact.getByRole('button', { name: '更多阅读设置' }).click();
    await expect(compact.getByRole('checkbox', { name: '窗口置顶', exact: true })).toBeChecked();
    await compact.getByLabel('进度显示', { exact: true }).selectOption('source');
    await expect.poll(() => app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find((window) => window.getTitle() === '资料').isAlwaysOnTop())).toBe(true);
    assert.match(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find((window) => window.getTitle() === '资料').getBackgroundColor()), /^#000000(?:00)?$/);
    await compact.getByRole('slider', { name: '背景透明度', exact: true }).press('End');
    await expect(compact.locator('.compact-reader')).toHaveCSS('background-color', 'rgba(250, 250, 248, 0)');
    await expect(compact.getByTestId('compact-text')).toHaveCSS('opacity', '1');
    const alpha = await app.evaluate(async ({ BrowserWindow }) => {
      const reader = BrowserWindow.getAllWindows().find((window) => window.getTitle() === '资料');
      const capture = await reader.webContents.capturePage({ x: 35, y: 1, width: 2, height: 2 });
      return capture.toBitmap()[3];
    });
    assert.equal(alpha, 0, 'Native reading background should have transparent pixels');
    await compact.getByRole('slider', { name: '背景透明度', exact: true }).press('Home');
    for (let step = 0; step < 13; step++) await compact.getByRole('slider', { name: '背景透明度', exact: true }).press('ArrowRight');
    await expect(compact.getByRole('slider', { name: '背景透明度', exact: true })).toHaveValue('65');
    await compact.getByRole('button', { name: '关闭阅读设置' }).click();
    await expect.poll(() => app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find((window) => window.getTitle() === '资料').getContentBounds().height)).toBe(36);
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find((window) => window.getTitle() === '资料').setPosition(220, 210));
    savedBounds = await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find((window) => window.getTitle() === '资料').getBounds());
    await compact.waitForFunction(() => speechSynthesis.getVoices().some((voice) => voice.localService));
    await compact.getByRole('button', { name: '开始朗读', exact: true }).click();
    await expect(compact.getByLabel('单行朗读状态')).toContainText('正在朗读');
    await compact.getByRole('button', { name: '暂停朗读', exact: true }).click();
    await expect(compact.getByLabel('单行朗读状态')).toContainText('已暂停');
    await compact.getByRole('button', { name: '继续朗读', exact: true }).click();
    await expect(compact.getByLabel('单行朗读状态')).toContainText('正在朗读');
    const beforeReload = await text.textContent();
    await selectLine(); await compact.getByRole('button', { name: '添加笔记', exact: true }).click();
    await compact.getByLabel('划线笔记内容').fill('收起时需要清除的草稿');
    await compact.keyboard.press('Escape');
    await expect(compact.getByRole('dialog', { name: '单行划线操作' })).toHaveCount(0);
    await expect(compact.getByRole('button', { name: '资料 · 点击恢复' })).toBeVisible();
    await expect(compact.getByTestId('compact-progress')).toHaveCount(0);
    await expect(compact.getByLabel('单行朗读状态')).toContainText('声音已停止');
    await compact.reload();
    await expect(compact.getByRole('button', { name: '资料 · 点击恢复' })).toBeVisible();
    await compact.getByRole('button', { name: '资料 · 点击恢复' }).click();
    await expect(text).toHaveText(beforeReload);
    await expect(compact.getByRole('button', { name: '开始朗读', exact: true })).toBeVisible();
    savedText = await text.textContent();
    savedProgress = await compact.getByTestId('compact-progress').textContent();
    const anchorId = await text.getAttribute('data-paragraph-id');
    await compact.screenshot({ path: 'release/compact-reader.png' });
    await compact.getByRole('button', { name: '更多阅读设置' }).click();
    await compact.getByRole('button', { name: '返回完整阅读' }).click();
    await expect(main).toHaveURL(new RegExp(`#paragraph-${anchorId}$`));
    await expect(main.locator(`#paragraph-${anchorId}`)).toBeInViewport();
    await expect(main.getByText('单行窗口里的原文批注。', { exact: true })).toHaveCount(1);
    await app.close(); app = null;
    app = await electron.launch({ executablePath, env, timeout: 60000 });
    const reopenedMain = await app.firstWindow();
    await reopenedMain.getByRole('heading', { name: '我的书架', exact: true }).waitFor();
    await reopenedMain.goto(new URL(sourcePath, reopenedMain.url()).toString());
    const windowReady = app.waitForEvent('window');
    await reopenedMain.evaluate(path => window.duobookDesktop.openCompactReader(path), '/compact' + sourcePath);
    const reopenedCompact = await windowReady;
    await expect(reopenedCompact.getByTestId('compact-text')).toHaveText(savedText);
    await expect(reopenedCompact.getByTestId('compact-progress')).toHaveText(savedProgress);
    const bounds = await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find((window) => window.getTitle() === '资料').getBounds());
    assert.equal(bounds.x, savedBounds.x); assert.equal(bounds.y, savedBounds.y); assert.equal(bounds.height, 36);
    assert.equal(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find((window) => window.getTitle() === '资料').isAlwaysOnTop()), true);
    await reopenedCompact.getByRole('button', { name: '更多阅读设置' }).click();
    await expect(reopenedCompact.getByRole('slider', { name: '背景透明度', exact: true })).toHaveValue('65');
    await expect(reopenedCompact.getByLabel('进度显示', { exact: true })).toHaveValue('source');
    await reopenedCompact.getByRole('checkbox', { name: '窗口置顶', exact: true }).uncheck();
    await expect.poll(() => app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find((window) => window.getTitle() === '资料').isAlwaysOnTop())).toBe(false);
    await reopenedCompact.getByRole('button', { name: '关闭阅读设置' }).click();
    await expect(reopenedCompact.getByRole('button', { name: '开始朗读', exact: true })).toBeVisible();
    assert.ok(fs.existsSync(path.join(data, 'compact-reader.json')));
    console.log('Compact native smoke passed: 600×36 window, native drag region, navigation, local speech, conceal/reload, return anchor, bounds/reading-position restart, pin on/off, transparent native pixels and background preference restart.');
    console.log('Isolated test data:', data);
  } finally { if (app) await app.close(); }
})().catch((error) => { console.error(error); process.exit(1); });
